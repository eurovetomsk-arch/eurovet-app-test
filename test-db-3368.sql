create or replace function public.ev_collection_transit_list(
  p_token text, p_branch text, p_date date
) returns jsonb
language plpgsql security definer set search_path=''
as $function$
declare
  v_pid bigint := public.ev_session_person(p_token);
  v_head boolean;
  v_items jsonb;
  v_total numeric;
begin
  if v_pid is null then return jsonb_build_object('ok',false,'error','session'); end if;
  v_head := public.ev__is_head(v_pid);
  if p_date is null or p_date < public.ev_today()-31 or p_date > public.ev_today() then
    return jsonb_build_object('ok',false,'error','period');
  end if;
  if not v_head and (p_branch is null or not public.ev__can_report(v_pid) or not public.ev__access_scope(p_token,p_branch,p_date)) then
    return jsonb_build_object('ok',false,'error','forbidden');
  end if;
  select coalesce(jsonb_agg(jsonb_build_object(
      'id',x.id,'branch',x.branch_id,'date',x.event_date,'amount',x.amount,'source',x.source,
      'recipient',x.recipient,'status',x.status,'confirmed_amount',x.confirmed_amount,
      'version',x.report_version,'created_at',x.created_at,'by',p.short_name
    ) order by x.created_at desc),'[]'::jsonb), coalesce(sum(x.amount),0)
    into v_items,v_total
    from public.ev_collection_transit x
    left join public.ev_people p on p.id=x.created_by
   where x.event_date=p_date and x.status<>'cancelled' and (p_branch is null or x.branch_id=p_branch);
  return jsonb_build_object('ok',true,'date',p_date,'branch',p_branch,'total',v_total,'items',v_items);
end $function$;

create or replace function public.ev_collection_reconcile_report()
returns trigger
language plpgsql security definer set search_path=''
as $function$
declare
  v_expected numeric;
  v_declared numeric;
  v_status text;
begin
  if new.branch_id='test' then return new; end if;
  select coalesce(sum(amount),0) into v_expected
    from public.ev_collection_transit
   where branch_id=new.branch_id and event_date=new.report_date and status<>'cancelled';
  if v_expected=0 then return new; end if;
  v_declared := public.ev__mr_sum(new.data);
  v_status := case when abs(v_expected-v_declared)<=10 then 'matched' else 'mismatch' end;
  update public.ev_collection_transit
     set status=v_status, confirmed_amount=v_declared, report_version=new.version, confirmed_at=now()
   where branch_id=new.branch_id and event_date=new.report_date and status<>'cancelled';
  return new;
end $function$;

drop trigger if exists ev_collection_reconcile_report on public.ev_reports;
create trigger ev_collection_reconcile_report
after insert on public.ev_reports
for each row execute function public.ev_collection_reconcile_report();

create or replace function public.ev_safe_out_add_v2(
  p_token text, p_amount numeric, p_date date, p_purpose text, p_note text, p_uid text
) returns jsonb
language plpgsql security definer set search_path=''
as $function$
declare
  v bigint := public.ev_session_person(p_token);
  v_id bigint;
  v_today date := public.ev_today();
  v_amt numeric;
begin
  if v is null then return jsonb_build_object('ok',false,'error','session'); end if;
  if not public.ev__is_head(v) then return jsonb_build_object('ok',false,'error','forbidden'); end if;
  if p_amount is null or p_amount<0.01 or p_amount>5000000 or p_date is null or p_date<date '2026-10-16' or p_date>v_today
     or p_purpose not in ('salary','other') or p_uid is null or length(p_uid)<8 then
    return jsonb_build_object('ok',false,'error','input');
  end if;
  v_amt := round(p_amount,2);
  insert into public.ev_safe_out(taken_on,amount,purpose,note,created_by,client_uid)
  values(p_date,v_amt,p_purpose,left('['||case when p_purpose='salary' then 'зарплата' else 'другое' end||'] '||coalesce(p_note,''),300),v,p_uid)
  on conflict(client_uid) where client_uid is not null do nothing returning id into v_id;
  insert into public.ev_access_log(person_id,action,ok,detail)
  values(v,'safe_out_add_v2',true,p_date::text||' '||v_amt::text||' '||p_purpose);
  return jsonb_build_object('ok',true,'id',v_id,'duplicate',v_id is null,'purpose',p_purpose);
end $function$;

create or replace function public.ev_my_cash_today(p_token text)
returns jsonb
language plpgsql security definer set search_path=''
as $function$
declare
  v bigint := public.ev_session_person(p_token);
  d date := public.ev_today();
  v_col numeric;
  v_safe numeric;
  v_paid numeric;
begin
  if v is null then return jsonb_build_object('ok',false,'error','session'); end if;
  if not public.ev__is_head(v) then return jsonb_build_object('ok',false,'error','forbidden'); end if;
  select coalesce(sum(amount),0) into v_col from public.ev_collection_transit
   where event_date=d and status<>'cancelled' and (source='head' or lower(coalesce(recipient,'')) like 'михаил%');
  select coalesce(sum(amount),0) into v_safe from public.ev_safe_out
   where taken_on=d and cancelled_at is null;
  select coalesce(sum(amount),0) into v_paid from public.ev_payroll_paid
   where pay_date=d and cancelled_at is null and method='cash';
  return jsonb_build_object('ok',true,'date',d,'collections',v_col,'safe_out',v_safe,'cash_payroll',v_paid,
                            'on_hand',v_col+v_safe-v_paid);
end $function$;

