set local ev.allow_ddl = 'on';

create table if not exists public.ev_collection_transit (
  id bigint generated by default as identity primary key,
  branch_id text not null references public.ev_branches(id),
  event_date date not null,
  amount numeric(14,2) not null check (amount >= 0.01 and amount <= 5000000),
  source text not null check (source in ('admin','head')),
  recipient text,
  status text not null default 'in_transit' check (status in ('in_transit','matched','mismatch','cancelled')),
  confirmed_amount numeric(14,2),
  report_version integer,
  created_by bigint not null references public.ev_people(id),
  created_at timestamptz not null default now(),
  confirmed_at timestamptz,
  cancelled_at timestamptz,
  client_uid text not null unique
);

create index if not exists ev_collection_transit_day_idx
  on public.ev_collection_transit(event_date, branch_id, status);
alter table public.ev_collection_transit enable row level security;
revoke all on table public.ev_collection_transit from public, anon, authenticated;
revoke all on sequence public.ev_collection_transit_id_seq from public, anon, authenticated;

alter table public.ev_safe_out
  add column if not exists purpose text not null default 'other'
  check (purpose in ('salary','other'));

create or replace function public.ev_collection_handoff(
  p_token text, p_branch text, p_amount numeric, p_recipient text, p_uid text
) returns jsonb
language plpgsql security definer set search_path=''
as $function$
declare
  v_pid bigint := public.ev_session_person(p_token);
  v_id bigint;
  v_today date := public.ev_today();
  v_amount numeric;
begin
  if v_pid is null then return jsonb_build_object('ok',false,'error','session'); end if;
  if not public.ev__can_report(v_pid) or not public.ev__access_scope(p_token,p_branch,v_today) then
    return jsonb_build_object('ok',false,'error','forbidden');
  end if;
  if p_branch is null or p_branch='test' or p_amount is null or p_amount < 0.01 or p_amount > 5000000
     or nullif(trim(p_recipient),'') is null or length(trim(p_recipient)) > 80
     or p_uid is null or length(p_uid) < 8 then
    return jsonb_build_object('ok',false,'error','input');
  end if;
  v_amount := round(p_amount,2);
  insert into public.ev_collection_transit(branch_id,event_date,amount,source,recipient,created_by,client_uid)
  values(p_branch,v_today,v_amount,'admin',left(trim(p_recipient),80),v_pid,p_uid)
  on conflict(client_uid) do nothing returning id into v_id;
  return jsonb_build_object('ok',true,'id',v_id,'duplicate',v_id is null,'date',v_today,'amount',v_amount,'status','in_transit');
end $function$;

create or replace function public.ev_collection_pickup(
